#!/usr/bin/env node
// Generates the workspace's HeroUI theme from the theme builder's knobs.
//
// The builder at https://heroui.com/en/themes?template=finances&hue=149.32371632910446&base=0.0074
// derives every colour from two numbers: the hue the accent and the greys share, and how much colour the greys carry.
// HeroUI ships its default theme as CSS variables, so the same derivation runs over that file and writes a theme of
// our own. Re-run with `pnpm theme:heroui`; the output is committed.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

export const THEME = {
  source: "https://heroui.com/en/themes?template=finances&hue=149.32371632910446&base=0.0074",
  template: "finances",
  hue: 149.32371632910446,
  base: 0.0074,
  accentLightness: 0.6204,
  accentChroma: 0.195,
  radius: "0.5rem",
  fieldRadius: "0.75rem",
  font: "Inter"
};

// A colour this dull is a grey the builder tints with the theme's own chroma and hue; anything more saturated is a
// status colour the builder leaves alone.
const GREY_CHROMA = 0.02;

const neutral = (lightness, chroma, hue) => `oklch(${lightness} ${chroma} ${hue})`;

function tintGreys(css, theme) {
  return css.replace(/oklch\(\s*([\d.]+%?)\s+([\d.]+)\s+([\d.]+)\s*\)/g, (match, lightness, chroma, hue) => {
    if (Number(chroma) > GREY_CHROMA) return match;
    return neutral(lightness, theme.base, theme.hue);
  });
}

export function buildTheme(defaults, theme = THEME) {
  const tinted = tintGreys(defaults, theme);
  const withAccent = tinted
    .replace(/--accent:\s*[^;]+;/, `--accent: ${neutral(theme.accentLightness, theme.accentChroma, theme.hue)};`)
    .replace(/--radius:\s*[^;]+;/, `--radius: ${theme.radius};`)
    .replace(/--field-radius:\s*[^;]+;/, `--field-radius: ${theme.fieldRadius};`);
  return `/* Generated by tools/heroui-theme.mjs. Do not edit by hand.
 * Builder: ${theme.source}
 * Template ${theme.template}, hue ${theme.hue}, base ${theme.base}, font ${theme.font}.
 */
${withAccent.trim()}\n`;
}

function main() {
  const source = resolve(root, "node_modules/@heroui/styles/dist/themes/default/variables.css");
  const target = resolve(root, "apps/web/src/theme/heroui-theme.css");
  const defaults = readFileSync(source, "utf8");
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, buildTheme(defaults), "utf8");
  console.log(`Wrote ${target} from ${THEME.source}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
